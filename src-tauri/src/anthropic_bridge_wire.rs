//! The supported Anthropic Messages subset translated to OpenAI chat wire.
//! Unsupported blocks fail explicitly rather than losing task context.
use serde_json::{json, Value};
use std::collections::BTreeMap;
use std::io::{self, BufRead, Read};

fn text_blocks(value: &Value) -> Result<String, String> {
    if let Some(text) = value.as_str() {
        return Ok(text.into());
    }
    let mut texts = Vec::new();
    for block in value.as_array().ok_or("Expected text or content blocks.")? {
        if block["type"] != "text" {
            return Err("This content block is not supported by the Nous bridge.".into());
        }
        texts.push(block["text"].as_str().ok_or("Missing block text.")?);
    }
    Ok(texts.join("\n"))
}
pub fn request(input: &Value) -> Result<Value, String> {
    let model = input["model"].as_str().ok_or("Missing model.")?;
    let mut messages = Vec::new();
    if let Some(system) = input.get("system") {
        messages.push(json!({"role":"system", "content":text_blocks(system)?}));
    }
    for message in input["messages"].as_array().ok_or("Missing messages.")? {
        let role = message["role"].as_str().ok_or("Missing message role.")?;
        if role == "system" {
            messages.push(json!({"role":"system","content":text_blocks(&message["content"])?}));
            continue;
        }
        if !matches!(role, "user" | "assistant") {
            return Err(format!("Unsupported message role: {role}."));
        }
        if message["content"].is_string() {
            messages.push(json!({"role":role,"content":message["content"]}));
            continue;
        }
        let mut content = Vec::new();
        let mut calls = Vec::new();
        let mut results = Vec::new();
        for block in message["content"]
            .as_array()
            .ok_or("Missing content blocks.")?
        {
            match block["type"].as_str().unwrap_or("") {
                "text" => content.push(json!({"type":"text","text":block["text"]})),
                "image" => {
                    let source = &block["source"];
                    let url = match source["type"].as_str() {
                        Some("base64") => format!("data:{};base64,{}", source["media_type"].as_str().ok_or("Missing image media type.")?, source["data"].as_str().ok_or("Missing image data.")?),
                        Some("url") => source["url"].as_str().ok_or("Missing image URL.")?.into(),
                        _ => return Err("Unsupported image source.".into()),
                    };
                    content.push(json!({"type":"image_url","image_url":{"url":url}}));
                }
                "tool_use" if role == "assistant" => calls.push(json!({"id":block["id"],"type":"function","function":{"name":block["name"],"arguments":block["input"].to_string()}})),
                "tool_result" if role == "user" => results.push(json!({"role":"tool","tool_call_id":block["tool_use_id"],"content":text_blocks(block.get("content").unwrap_or(&Value::String(String::new())))?})),
                // Thinking is not generated by this bridge. Reject signed/replayed
                // native thinking instead of feeding an invalid signature upstream.
                _ => return Err(format!("Unsupported content block: {}. Start a new conversation for this intelligence source.", block["type"])),
            }
        }
        // Results must immediately follow their assistant tool calls. A user
        // message may also carry text after the results.
        messages.extend(results);
        if !content.is_empty() || !calls.is_empty() {
            let mut next = json!({"role":role,"content":if content.is_empty() { Value::Null } else { Value::Array(content) }});
            if !calls.is_empty() {
                next["tool_calls"] = json!(calls);
            }
            messages.push(next);
        }
    }
    let mut out = json!({"model":model,"messages":messages,"max_tokens":input["max_tokens"],"stream":input["stream"].as_bool().unwrap_or(false)});
    for key in ["temperature", "top_p"] {
        if let Some(v) = input.get(key) {
            out[key] = v.clone();
        }
    }
    if let Some(stops) = input.get("stop_sequences") {
        out["stop"] = stops.clone();
    }
    if let Some(tools) = input.get("tools").and_then(Value::as_array) {
        let mut mapped = Vec::new();
        for tool in tools {
            if tool.get("type").is_some_and(|v| v != "custom") {
                return Err("Server-side Anthropic tools are not supported by this bridge.".into());
            }
            mapped.push(json!({"type":"function","function":{"name":tool["name"],"description":tool.get("description").cloned().unwrap_or(json!("")),"parameters":tool["input_schema"]}}));
        }
        if !mapped.is_empty() {
            out["tools"] = json!(mapped);
        }
    }
    if let Some(choice) = input.get("tool_choice") {
        out["tool_choice"] = match choice["type"].as_str() {
            Some("auto") => json!("auto"),
            Some("any") => json!("required"),
            Some("none") => json!("none"),
            Some("tool") => json!({"type":"function","function":{"name":choice["name"]}}),
            _ => return Err("Unsupported tool choice.".into()),
        };
        if let Some(disable) = choice
            .get("disable_parallel_tool_use")
            .and_then(Value::as_bool)
        {
            out["parallel_tool_calls"] = json!(!disable);
        }
    }
    if input
        .get("output_config")
        .and_then(|v| v.get("format"))
        .is_some()
    {
        return Err("Structured output formats are not supported by this bridge yet.".into());
    }
    if out["stream"] == true {
        out["stream_options"] = json!({"include_usage":true});
    }
    Ok(out)
}
fn reason(value: &str) -> &str {
    match value {
        "tool_calls" => "tool_use",
        "length" => "max_tokens",
        "stop" => "end_turn",
        _ => "end_turn",
    }
}
fn usage(value: &Value) -> Value {
    let cached = value["prompt_tokens_details"]["cached_tokens"]
        .as_u64()
        .unwrap_or(0);
    json!({"input_tokens":value["prompt_tokens"].as_u64().unwrap_or(0).saturating_sub(cached),"output_tokens":value["completion_tokens"].as_u64().unwrap_or(0),"cache_read_input_tokens":cached,"cache_creation_input_tokens":0})
}
/// Non-streamed reply; only the test-only Nous bridge server reads one.
#[cfg(test)]
pub fn response(value: &Value, model: &str) -> Result<Value, String> {
    let choice = value["choices"]
        .as_array()
        .and_then(|c| c.first())
        .ok_or("Upstream returned no model response.")?;
    let mut content = Vec::new();
    if let Some(text) = choice["message"]["content"]
        .as_str()
        .filter(|s| !s.is_empty())
    {
        content.push(json!({"type":"text","text":text}));
    }
    for tool in choice["message"]["tool_calls"]
        .as_array()
        .into_iter()
        .flatten()
    {
        let args: Value =
            serde_json::from_str(tool["function"]["arguments"].as_str().unwrap_or("{}"))
                .map_err(|_| "Upstream returned invalid tool arguments.")?;
        content.push(
            json!({"type":"tool_use","id":tool["id"],"name":tool["function"]["name"],"input":args}),
        );
    }
    Ok(
        json!({"id":value.get("id").cloned().unwrap_or(json!("msg_klide")),"type":"message","role":"assistant","model":model,"content":content,"stop_reason":reason(choice["finish_reason"].as_str().unwrap_or("stop")),"stop_sequence":null,"usage":usage(&value["usage"])}),
    )
}
fn event(kind: &str, value: Value) -> Vec<u8> {
    format!("event: {kind}\ndata: {value}\n\n").into_bytes()
}
#[derive(Default)]
struct Tool {
    index: usize,
    id: String,
    name: String,
    arguments: String,
    started: bool,
}
#[derive(Default)]
struct StreamState {
    next: usize,
    text: Option<usize>,
    tools: BTreeMap<u64, Tool>,
    stop: String,
    usage: Value,
}
impl StreamState {
    fn chunk(&mut self, chunk: &Value) -> Result<Vec<u8>, String> {
        if let Some(error) = chunk.get("error") {
            return Err(if error.is_null() {
                "Invalid Nous inference event."
            } else {
                "Nous inference failed. Check your subscription and model availability."
            }
            .into());
        }
        if chunk.get("usage").is_some_and(|v| !v.is_null()) {
            self.usage = chunk["usage"].clone();
        }
        let mut output = Vec::new();
        let Some(choice) = chunk["choices"].as_array().and_then(|c| c.first()) else {
            return Ok(output);
        };
        if let Some(stop) = choice["finish_reason"].as_str() {
            self.stop = stop.into();
        }
        let delta = &choice["delta"];
        if let Some(text) = delta["content"].as_str().filter(|s| !s.is_empty()) {
            let index = *self.text.get_or_insert_with(|| {
                let i = self.next;
                self.next += 1;
                i
            });
            output.extend(event("content_block_delta", json!({"type":"content_block_delta","index":index,"delta":{"type":"text_delta","text":text}})));
        }
        for call in delta["tool_calls"].as_array().into_iter().flatten() {
            let key = call["index"]
                .as_u64()
                .ok_or("Missing streamed tool index.")?;
            let tool = self.tools.entry(key).or_insert_with(|| {
                let index = self.next;
                self.next += 1;
                Tool {
                    index,
                    ..Default::default()
                }
            });
            if let Some(id) = call["id"].as_str() {
                tool.id.push_str(id);
            }
            if let Some(name) = call["function"]["name"].as_str() {
                tool.name.push_str(name);
            }
            if let Some(args) = call["function"]["arguments"].as_str() {
                tool.arguments.push_str(args);
            }
            if !tool.started && !tool.id.is_empty() && !tool.name.is_empty() {
                output.extend(event("content_block_start", json!({"type":"content_block_start","index":tool.index,"content_block":{"type":"tool_use","id":tool.id,"name":tool.name,"input":{}}})));
                tool.started = true;
            }
            if tool.started && !tool.arguments.is_empty() {
                output.extend(event("content_block_delta", json!({"type":"content_block_delta","index":tool.index,"delta":{"type":"input_json_delta","partial_json":tool.arguments}})));
                tool.arguments.clear();
            }
        }
        Ok(output)
    }
    fn finish(&self) -> Vec<u8> {
        let mut output = Vec::new();
        for index in 0..self.next {
            output.extend(event(
                "content_block_stop",
                json!({"type":"content_block_stop","index":index}),
            ));
        }
        output.extend(event("message_delta", json!({"type":"message_delta","delta":{"stop_reason":reason(&self.stop),"stop_sequence":null},"usage":usage(&self.usage)})));
        output.extend(event("message_stop", json!({"type":"message_stop"})));
        output
    }
}
/// Reads upstream SSE as it arrives; no full-turn buffering or extra request.
pub struct StreamReader<R: BufRead> {
    reader: R,
    pending: io::Cursor<Vec<u8>>,
    state: StreamState,
    done: bool,
    text_started: bool,
}
impl<R: BufRead> StreamReader<R> {
    pub fn new(reader: R, model: &str) -> Self {
        Self {
            reader,
            pending: io::Cursor::new(event(
                "message_start",
                json!({"type":"message_start","message":{"id":format!("msg_klide_{}", std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap_or_default().as_nanos()),"type":"message","role":"assistant","model":model,"content":[],"stop_reason":null,"stop_sequence":null,"usage":{"input_tokens":0,"output_tokens":0}}}),
            )),
            state: StreamState::default(),
            done: false,
            text_started: false,
        }
    }
    fn next(&mut self) -> Result<Vec<u8>, String> {
        let mut data = String::new();
        loop {
            let mut line = String::new();
            if self
                .reader
                .read_line(&mut line)
                .map_err(|_| "Nous inference stream was interrupted.")?
                == 0
            {
                return Err("Nous inference stream ended before its completion marker.".into());
            }
            if line.trim().is_empty() {
                if !data.is_empty() {
                    break;
                } else {
                    continue;
                }
            }
            if let Some(value) = line.strip_prefix("data:") {
                data.push_str(value.trim());
            }
            if data.len() > 16 * 1024 * 1024 {
                return Err("Upstream event is too large.".into());
            }
        }
        if data == "[DONE]" {
            if self.state.stop.is_empty() {
                return Err("Nous stream omitted its completion reason.".into());
            }
            if self.state.tools.values().any(|tool| !tool.started) {
                return Err("Nous stream returned an incomplete tool call.".into());
            }
            self.done = true;
            return Ok(self.state.finish());
        }
        let chunk: Value =
            serde_json::from_str(&data).map_err(|_| "Invalid Nous inference event.")?;
        let mut out = Vec::new();
        if !self.text_started
            && chunk["choices"][0]["delta"]["content"]
                .as_str()
                .is_some_and(|s| !s.is_empty())
        {
            self.text_started = true;
            out.extend(event("content_block_start", json!({"type":"content_block_start","index":self.state.next,"content_block":{"type":"text","text":""}})));
        }
        out.extend(self.state.chunk(&chunk)?);
        Ok(out)
    }
}
impl<R: BufRead> Read for StreamReader<R> {
    fn read(&mut self, buf: &mut [u8]) -> io::Result<usize> {
        if buf.is_empty() {
            return Ok(0);
        }
        loop {
            let n = self.pending.read(buf)?;
            if n > 0 || self.done {
                return Ok(n);
            }
            let bytes = match self.next() {
                Ok(bytes) => bytes,
                Err(error) => {
                    self.done = true;
                    event(
                        "error",
                        json!({"type":"error","error":{"type":"api_error","message":error}}),
                    )
                }
            };
            self.pending = io::Cursor::new(bytes);
        }
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn roundtrip_tool_calls_results_and_images() {
        let out = request(&json!({"model":"anthropic/claude-sonnet-test","max_tokens":128,"system":[{"type":"text","text":"Code"}],"messages":[{"role":"assistant","content":[{"type":"tool_use","id":"t1","name":"Read","input":{"path":"app.rs"}}]},{"role":"user","content":[{"type":"tool_result","tool_use_id":"t1","content":"hello"},{"type":"text","text":"Continue"}]}],"tools":[{"name":"Read","input_schema":{"type":"object"}}],"tool_choice":{"type":"any"}})).unwrap();
        assert_eq!(
            out["messages"][1]["tool_calls"][0]["function"]["arguments"],
            r#"{"path":"app.rs"}"#
        );
        assert_eq!(out["messages"][2]["role"], "tool");
        assert_eq!(out["messages"][3]["content"][0]["text"], "Continue");
        assert_eq!(out["tool_choice"], "required");
        let back = response(&json!({"choices":[{"message":{"tool_calls":[{"id":"t2","function":{"name":"Read","arguments":"{\"path\":\"app.rs\"}"}}]},"finish_reason":"tool_calls"}],"usage":{"prompt_tokens":100,"completion_tokens":20,"prompt_tokens_details":{"cached_tokens":50}}}), "claude-test").unwrap();
        assert_eq!(back["stop_reason"], "tool_use");
        assert_eq!(back["content"][0]["input"]["path"], "app.rs");
        assert_eq!(back["usage"]["input_tokens"], 50);
    }
    #[test]
    fn streaming_preserves_fragmented_tools_usage_and_errors() {
        let chunks = [
            json!({"choices":[{"delta":{"content":"Hi"}}]}),
            json!({"choices":[{"delta":{"tool_calls":[{"index":0,"id":"t1","function":{"name":"Read","arguments":"{\"path\":"}}]}}]}),
            json!({"choices":[{"delta":{"tool_calls":[{"index":0,"function":{"arguments":"\"app.rs\"}"}}]},"finish_reason":"tool_calls"}]}),
            json!({"choices":[],"usage":{"prompt_tokens":42,"completion_tokens":9}}),
        ];
        let mut wire = chunks
            .iter()
            .map(|v| format!("data: {v}\n\n"))
            .collect::<String>();
        wire.push_str("data: [DONE]\n\n");
        let mut reader = StreamReader::new(io::Cursor::new(wire), "claude-test");
        let mut out = String::new();
        reader.read_to_string(&mut out).unwrap();
        assert_eq!(out.matches("event: content_block_start").count(), 2);
        assert!(out.contains("input_json_delta"));
        assert!(out.contains("\"stop_reason\":\"tool_use\""));
        assert!(out.contains("\"output_tokens\":9"));
        assert!(out.ends_with("event: message_stop\ndata: {\"type\":\"message_stop\"}\n\n"));
        let mut reader = StreamReader::new(io::Cursor::new("data: broken\n\n"), "claude-test");
        out.clear();
        reader.read_to_string(&mut out).unwrap();
        assert!(out.contains("event: error"));
        assert!(!out.contains("message_stop"));
    }
    #[test]
    fn supplemental_system_messages_are_preserved() {
        let out = request(&json!({"model":"claude-test","max_tokens":128,"system":"Base","messages":[{"role":"user","content":"Question"},{"role":"system","content":[{"type":"text","text":"Supplement"}]}]})).unwrap();
        assert_eq!(out["messages"][0]["content"], "Base");
        assert_eq!(out["messages"][2]["role"], "system");
        assert_eq!(out["messages"][2]["content"], "Supplement");
    }
    #[test]
    fn unsupported_context_is_rejected() {
        assert!(request(&json!({"model":"claude-test","messages":[{"role":"assistant","content":[{"type":"thinking","thinking":"secret","signature":"native"}]}]})).is_err());
    }
}
