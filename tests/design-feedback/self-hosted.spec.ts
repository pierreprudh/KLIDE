import { expect, test } from "@playwright/test";

test("Tailscale shortcut discovers models, saves, and edits as an ordinary API", async ({ page }, testInfo) => {
  await page.goto("/preview/self-hosted.html");
  await page.getByRole("button", { name: "+ Add self-hosted endpoint" }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Endpoint name", { exact: true }).fill("Lab GPU");
  await dialog.getByRole("button", { name: "Tailscale quick setup" }).click();
  await dialog.getByLabel("Tailscale IP or machine name").fill("gpu-box");
  await expect(dialog.getByText("http://gpu-box:8000/v1", { exact: true })).toBeVisible();
  await dialog.getByLabel("API port", { exact: true }).fill("65536");
  await expect(dialog.getByRole("button", { name: "Test connection" })).toBeDisabled();
  await expect(dialog.getByRole("button", { name: "Add endpoint", exact: true })).toBeDisabled();
  await dialog.getByLabel("API port", { exact: true }).fill("8080");
  await expect(dialog.getByRole("button", { name: "Tailscale quick setup" })).toHaveAttribute("aria-pressed", "true");
  await page.screenshot({ path: testInfo.outputPath("tailscale-light.png"), animations: "disabled" });
  await dialog.getByRole("button", { name: "Test connection" }).click();
  await expect(dialog.getByRole("status")).toContainText("2 chat models");
  await dialog.getByRole("combobox").selectOption("coding-model");
  await dialog.getByLabel("Tailscale IP or machine name").fill("gpu-box-2.tail123.ts.net");
  await expect(dialog.getByRole("status")).toHaveCount(0);
  await dialog.getByRole("button", { name: "API URL", exact: true }).click();
  await expect(dialog.getByLabel("API base URL", { exact: true })).toHaveValue("http://gpu-box-2.tail123.ts.net:8080/v1");
  await dialog.getByRole("button", { name: "Add endpoint", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByText("gpu-box-2.tail123.ts.net:8080", { exact: true })).toBeVisible();
  await expect(page.getByText("gpu-box-2.tail123.ts.net:8080 · coding-model", { exact: true })).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath("endpoint-row.png"), animations: "disabled" });
  await page.getByRole("button", { name: "Edit endpoint", exact: true }).click();
  await expect(dialog.getByLabel("API base URL", { exact: true })).toHaveValue("http://gpu-box-2.tail123.ts.net:8080/v1");
  await expect(dialog.getByLabel("Endpoint name", { exact: true })).toHaveValue("Lab GPU");
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
});

test("API URL preserves custom paths and errors, and fits a narrow screen", async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 700 });
  await page.goto("/preview/self-hosted.html?theme=cursor-dark");
  await page.getByRole("button", { name: "+ Add self-hosted endpoint" }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByLabel("Endpoint name", { exact: true })).toBeFocused();
  await dialog.getByRole("button", { name: "API URL", exact: true }).focus();
  await page.keyboard.press("Shift+Tab");
  await expect(dialog.getByRole("button", { name: "Cancel", exact: true })).toBeFocused();
  await page.keyboard.press("Tab");
  await expect(dialog.getByRole("button", { name: "API URL", exact: true })).toBeFocused();
  await dialog.getByLabel("Endpoint name", { exact: true }).fill("Private API");
  await dialog.getByLabel("API base URL", { exact: true }).fill("https://offline.example/api/v1");
  await dialog.getByRole("button", { name: "Test connection" }).click();
  await expect(dialog.getByRole("alert")).toContainText("Could not reach");
  await dialog.getByLabel("API base URL", { exact: true }).fill("https://llm.example/api/v1");
  await expect(dialog.getByRole("alert")).toHaveCount(0);
  await dialog.getByLabel("API token reference (optional)", { exact: true }).fill("raw-token");
  await dialog.getByRole("button", { name: "Add endpoint", exact: true }).click();
  await expect(dialog.getByRole("alert")).toContainText("Use a ${VAR} reference");
  await dialog.getByLabel("API token reference (optional)", { exact: true }).fill("${LAB_KEY}");
  await expect(dialog).toBeVisible();
  expect(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("api-narrow-dark.png"), animations: "disabled" });
  await dialog.getByRole("button", { name: "Add endpoint", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await page.getByRole("button", { name: "Edit endpoint", exact: true }).click();
  await expect(dialog.getByLabel("API base URL", { exact: true })).toHaveValue("https://llm.example/api/v1");
  await expect(dialog.getByLabel("API token reference (optional)", { exact: true })).toHaveValue("${LAB_KEY}");
});
